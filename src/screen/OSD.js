const OSD_GREEN = '#5dff6a';
// Keep text inside the title-safe area: the bezel and overscan crop the edges.
const SAFE_X = 84;
const SAFE_Y = 64;

// The TV's own on-screen display: a green channel number and a closed-caption
// style lower third. Drawn into a transparent canvas the size of the signal.
export class OSD {
  constructor() {
    this.canvas = document.createElement('canvas');
    this.canvas.width = SIGNAL_WIDTH;
    this.canvas.height = SIGNAL_HEIGHT;
    this.ctx = this.canvas.getContext('2d');
    this.texture = new THREE.CanvasTexture(this.canvas);
    this.texture.generateMipmaps = false;
    this.texture.minFilter = THREE.LinearFilter;

    this.channel = null;
    this.caption = '';
    this.hold = 0;
    this.opacity = 0;
    this.pinned = false;
  }

  show(channel, caption = '', hold = 2.5) {
    this.channel = channel;
    this.caption = caption;
    this.hold = hold;
    this.opacity = 1;
    this.draw();
  }

  update(dt) {
    if (this.pinned) {
      this.opacity = 1;
      return this.opacity;
    }
    this.hold -= dt;
    if (this.hold <= 0) this.opacity = Math.max(0, this.opacity - dt * 3);
    return this.opacity;
  }

  draw() {
    const { ctx, canvas } = this;
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    if (this.channel !== null) {
      const label = `CH ${String(this.channel).padStart(2, '0')}`;
      const scale = 6;
      const x = canvas.width - SAFE_X - measure(label, scale);
      drawText(ctx, label, x, SAFE_Y, scale, OSD_GREEN, '#000');
    }

    if (this.caption) {
      const text = this.caption.toUpperCase();
      const scale = 3;
      const width = measure(text, scale);
      const x = Math.max(SAFE_X, (canvas.width - width) / 2);
      const y = canvas.height - SAFE_Y - 7 * scale - 24;
      ctx.fillStyle = '#000';
      ctx.fillRect(x - 9, y - 9, Math.min(width, canvas.width - SAFE_X * 2) + 18, 7 * scale + 18);
      drawText(ctx, text, x, y, scale, '#f4f4f0', null);
    }

    this.texture.needsUpdate = true;
  }
}

function measure(text, scale) {
  return text.length * 6 * scale - scale;
}

function drawText(ctx, text, x, y, scale, color, outline) {
  const pixels = [];
  [...text.toUpperCase()].forEach((char, i) => {
    const rows = GLYPHS[char] ?? GLYPHS['?'];
    const gx = x + i * 6 * scale;
    rows.forEach((bits, row) => {
      for (let col = 0; col < 5; col++) {
        if (bits & (0x10 >> col)) pixels.push([gx + col * scale, y + row * scale]);
      }
    });
  });

  // Real OSDs edge characters in black so they read over any picture.
  if (outline) {
    ctx.fillStyle = outline;
    const o = Math.max(2, scale / 2);
    pixels.forEach(([px, py]) => ctx.fillRect(px - o, py - o, scale + o * 2, scale + o * 2));
  }
  ctx.fillStyle = color;
  pixels.forEach(([px, py]) => ctx.fillRect(px, py, scale, scale));
}
